import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

// Compile the exact server-side simulation and route engine for the standalone
// browser preview. The generated module is shipped so previews need no install.
await build({
  entryPoints: [fileURLToPath(new URL('../../backend/sample/service.js', import.meta.url))],
  outfile: fileURLToPath(new URL('../src/services/generated/sample-service.js', import.meta.url)),
  bundle: true, platform: 'browser', format: 'esm', target: 'es2022',
  banner: { js: '// GENERATED by npm run build:sample-service. Edit backend/sample/service.js instead.' },
  plugins: [{
    name: 'browser-performance-clock',
    setup(builder) {
      builder.onResolve({ filter: /^node:perf_hooks$/ }, () => ({ path: 'clock', namespace: 'browser-clock' }));
      builder.onLoad({ filter: /.*/, namespace: 'browser-clock' }, () => ({ contents: 'export const performance = globalThis.performance;' }));
    },
  }],
});
